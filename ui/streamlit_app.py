with c1:
    if st.button("Generate AI Fix Suggestion", use_container_width=True):
        if not code_source:
            st.error("Run a review first, then request AI fix suggestions.")
        else:
            with st.spinner("Asking AI for fix suggestions..."):
                try:
                    st.session_state["ai_fix_md"] = ai_fix_suggestions(code_source, issues_source)
                except Exception as e:
                    st.session_state["ai_fix_md"] = f"AI suggestions failed: {e}"

    if st.session_state["ai_fix_md"]:
        st.markdown(st.session_state["ai_fix_md"])

with c2:
    if st.button("Show Auto-Fixed Code (safe)", use_container_width=True):
        if not code_source:
            st.error("Run a review first, then show auto-fixed code.")
        else:
            with st.spinner("Applying auto-fixes..."):
                try:
                    fixed_code, applied_fixes = apply_auto_fixes(code_source, issues_source)
                    st.session_state["fixed_code"] = fixed_code
                    st.session_state["applied_fixes"] = applied_fixes
                except Exception as e:
                    st.error(f"Auto-fix failed: {e}")

    if st.session_state["fixed_code"]:
        st.subheader("Fixed Code")
        st.code(st.session_state["fixed_code"], language="python")
        if st.session_state["applied_fixes"]:
            st.info("Applied fixes:\n- " + "\n- ".join(st.session_state["applied_fixes"]))
        else:
            st.info("No safe auto-fixes were applied.")
        st.download_button(
            label="Download Fixed Code",
            data=st.session_state["fixed_code"].encode("utf-8"),
            file_name=display_name_source.replace(".py", "_fixed.py"),
            mime="text/x-python",
            use_container_width=True,
        )
